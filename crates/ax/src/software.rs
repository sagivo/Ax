// loop_sum — wrapping accumulate
// ---------------------------------------------------------------------------

fn run_loop_sum() -> Result<CaseResult, String> {
    const N: u64 = 80_000_000;
    let ax = format!(
        r#"
module bench.sw.loop_sum;
export {{ main }};
fn main() -> usz = {{
    let mut s: usz = 0;
    for i in range(0, {N}) {{
        s = s + i;
    }};
    s
}};
"#
    );
    let c = format!(
        r#"
#include <stdio.h>
#include <stdint.h>
#include <inttypes.h>
int main(void) {{
    uint64_t s = 0;
    for (uint64_t i = 0; i < {N}ull; i++) s += i;
    printf("%" PRIu64 "\n", s);
    return 0;
}}
"#
    );
    let rs = format!(
        r#"
fn main() {{
    let mut s = 0u64;
    let mut i = 0u64;
    while i < {N} {{
        s = s.wrapping_add(i);
        i += 1;
    }}
    println!("{{s}}");
}}
"#
    );
    let go = format!(
        r#"package main
import "fmt"
func main() {{
    var s uint64
    for i := uint64(0); i < {N}; i++ {{
        s += i
    }}
    fmt.Println(s)
}}
"#
    );
    let rows = time_langs("loop", &ax, &c, &rs, &go, &[])?;
    finish(
        "loop_sum",
        "loop sum",
        "Accumulate `0 + 1 + … + (n-1)` with wrapping integer add. The basic counted loop.",
        N,
        rows,
    )
}

// ---------------------------------------------------------------------------
// array_seq — fill a vector, sequential sum (BCE-friendly in Ax)
// ---------------------------------------------------------------------------

fn run_array_seq() -> Result<CaseResult, String> {
    const N: u64 = 8_000_000;
    let ax = format!(
        r#"
module bench.sw.array_seq;
export {{ main }};
fn main() -> u64 !{{alloc[r], diverge}} = region r {{
    let mut xs: Vec[u64] = vec.new(r);
    xs.reserve({N}usz);
    for i in range(0, {N}) {{
        xs.push(i as u64);
    }};
    let mut s: u64 = 0;
    for i in range(0, xs.len()) {{
        s = s + xs.at(i);
    }};
    s
}};
"#
    );
    let c = format!(
        r#"
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <inttypes.h>
int main(void) {{
    uint64_t n = {N}ull;
    uint64_t cap = n, len = 0;
    uint64_t *xs = malloc(cap * sizeof(uint64_t));
    for (uint64_t i = 0; i < n; i++) {{
        if (len == cap) {{ cap *= 2; xs = realloc(xs, cap * sizeof(uint64_t)); }}
        xs[len++] = i;
    }}
    uint64_t s = 0;
    for (uint64_t i = 0; i < len; i++) s += xs[i];
    printf("%" PRIu64 "\n", s);
    free(xs);
    return 0;
}}
"#
    );
    let rs = format!(
        r#"
fn main() {{
    let n: u64 = {N};
    let mut xs = Vec::with_capacity(n as usize);
    for i in 0..n {{ xs.push(i); }}
    let mut s = 0u64;
    for x in &xs {{ s = s.wrapping_add(*x); }}
    println!("{{s}}");
}}
"#
    );
    let go = format!(
        r#"package main
import "fmt"
func main() {{
    n := uint64({N})
    xs := make([]uint64, n)
    for i := uint64(0); i < n; i++ {{ xs[i] = i }}
    var s uint64
    for i := uint64(0); i < n; i++ {{ s += xs[i] }}
    fmt.Println(s)
}}
"#
    );
    let rows = time_langs("aseq", &ax, &c, &rs, &go, &[])?;
    finish(
        "array_seq",
        "array sequential",
        "Push n `u64`s, then sum them in index order. Ax's `for i in range(0, xs.len()) {{ xs.at(i) }}` is in-range, so the check can drop.",
        N,
        rows,
    )
}

// ---------------------------------------------------------------------------
// array_rand — fill, then gather with an LCG index
// ---------------------------------------------------------------------------

fn run_array_rand() -> Result<CaseResult, String> {
    const N: u64 = 2_000_000;
    let ax = format!(
        r#"
module bench.sw.array_rand;
export {{ main }};
fn main() -> u64 !{{alloc[r], diverge}} = region r {{
    let n: usz = {N};
    let mut xs: Vec[u64] = vec.new(r);
    xs.reserve(n);
    for i in range(0, n) {{
        xs.push(i as u64);
    }};
    let mut s: u64 = 0;
    let mut idx: usz = 1;
    for _ in range(0, n) {{
        idx = (idx * 6364136223846793005 + 1) % n;
        s = s + xs.at(idx);
    }};
    s
}};
"#
    );
    let c = format!(
        r#"
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <inttypes.h>
int main(void) {{
    uint64_t n = {N}ull;
    uint64_t *xs = malloc(n * sizeof(uint64_t));
    for (uint64_t i = 0; i < n; i++) xs[i] = i;
    uint64_t s = 0, idx = 1;
    for (uint64_t i = 0; i < n; i++) {{
        idx = idx * 6364136223846793005ull + 1;
        idx %= n;
        s += xs[idx];
    }}
    printf("%" PRIu64 "\n", s);
    free(xs);
    return 0;
}}
"#
    );
    let rs = format!(
        r#"
fn main() {{
    let n: u64 = {N};
    let mut xs = Vec::with_capacity(n as usize);
    for i in 0..n {{ xs.push(i); }}
    let mut s = 0u64;
    let mut idx = 1u64;
    for _ in 0..n {{
        idx = idx.wrapping_mul(6364136223846793005).wrapping_add(1) % n;
        s = s.wrapping_add(xs[idx as usize]);
    }}
    println!("{{s}}");
}}
"#
    );
    let go = format!(
        r#"package main
import "fmt"
func main() {{
    n := uint64({N})
    xs := make([]uint64, n)
    for i := uint64(0); i < n; i++ {{ xs[i] = i }}
    var s, idx uint64 = 0, 1
    for i := uint64(0); i < n; i++ {{
        idx = idx*6364136223846793005 + 1
        idx %= n
        s += xs[idx]
    }}
    fmt.Println(s)
}}
"#
    );
    let rows = time_langs("arand", &ax, &c, &rs, &go, &[])?;
    finish(
        "array_rand",
        "array random get",
        "Fill n `u64`s, then sum n gathers whose index is an LCG. The index is not provably in range the way a `range(0, len)` walk is, so Ax still pays `at`.",
        N,
        rows,
    )
}

