//! Common software-use-case wall-clock benches: Ax / C / Rust / Go.
//!
//! These are the shapes a program actually spends time in — loops, arrays,
//! strings, maps, sort, file IO, HTTP — not the synthetic compute kernels
//! in `bench metrics`. Same algorithm in every language; the harness refuses
//! to report a time unless every backend printed the same value.
//!
//! `ax bench software` writes `docs/software_usecases.md`.

use crate::bench::{
    bench_dir, compile_ax, compile_c, compile_go, compile_rust, ensure_payload, expect_same,
    fmt_ms, go_available, print_group, ratio, time_cmd_stats, workspace, Row,
};
use std::process::Command;
use std::time::Duration;

const ITERS: u32 = 11;
const WARMUP: u32 = 2;

struct CaseResult {
    id: &'static str,
    title: &'static str,
    what: &'static str,
    n: u64,
    ax: u128,
    c: u128,
    rust: u128,
    go: Option<u128>,
    #[allow(dead_code)]
    out: String,
}

fn within(ax: u128, other: u128) -> bool {
    // Process spawn is 1.5–2.6 ms on this machine and is included in every
    // sample. A 15% band is the smallest that does not flip a 2 ms loop
    // between "behind" and "parity" from one run to the next.
    ax as f64 <= other as f64 * 1.15
}

pub fn run() -> Result<(), String> {
    println!("Software use cases  (same algorithm, identical output, fastest of {ITERS})\n");
    println!("Backends:  c = cc -O3 -flto   rust = rustc -C opt-level=3 -C lto=thin");
    println!("           go = go build      ax  = ax build --tier release\n");

    let mut results = Vec::new();
    results.push(run_loop_sum()?);
    results.push(run_array_seq()?);
    results.push(run_array_rand()?);
    results.push(run_string_join()?);
    results.push(run_map_hist()?);
    results.push(run_sort_ints()?);
    results.push(run_file_read()?);
    results.push(run_file_write()?);
    results.push(run_http()?);

    let path = workspace().join("docs/software_usecases.md");
    if let Some(p) = path.parent() {
        std::fs::create_dir_all(p).map_err(|e| e.to_string())?;
    }
    let md = render_doc(&results);
    std::fs::write(&path, &md).map_err(|e| e.to_string())?;
    println!("wrote {}", path.display());

    let behind: Vec<_> = results
        .iter()
        .filter(|r| {
            let rust_ok = within(r.ax, r.rust);
            let c_ok = within(r.ax, r.c);
            let go_ok = r.go.map(|g| within(r.ax, g)).unwrap_or(true);
            !(rust_ok && c_ok && go_ok)
        })
        .map(|r| r.id)
        .collect();
    if behind.is_empty() {
        println!("\nAx is within 15% of C, Rust, and Go on every use case.");
    } else {
        println!(
            "\nAx is still behind on: {}. Iterate (see the findings log in the doc).",
            behind.join(", ")
        );
    }
    Ok(())
}

fn render_doc(rows: &[CaseResult]) -> String {
    let mut md = String::from(
        "# Software use-case benchmarks\n\n\
         Common shapes a program actually spends time in, measured the same way \
         as `ax bench metrics`: **same algorithm**, **identical printed value**, \
         **fastest of 11 runs** (process spawn included). Ratios below 1.00× mean \
         Ax was faster. A dash means that toolchain was absent.\n\n\
         This file is regenerated by `ax bench software`. The findings log at the \
         bottom is the record of what was slow, why, and what changed.\n\n\
         Toolchains: `cc -O3 -flto -fno-asynchronous-unwind-tables -DNDEBUG`, \
         `rustc -C opt-level=3 -C lto=thin -C codegen-units=1 -C panic=abort`, \
         `go build`, `ax build --tier release`.\n\n",
    );

    md.push_str("## Current results\n\n");
    md.push_str("| use case | n | ax | c | rust | go | ax/c | ax/rust | ax/go | verdict |\n");
    md.push_str("|---|---:|---:|---:|---:|---:|---:|---:|---:|---|\n");
    for r in rows {
        let v = verdict(r);
        md.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {:.2}× | {:.2}× | {} | {} |\n",
            r.title,
            fmt_n(r.n),
            fmt_ms(r.ax),
            fmt_ms(r.c),
            fmt_ms(r.rust),
            r.go.map(fmt_ms).unwrap_or_else(|| "—".into()),
            ratio(r.ax, r.c),
            ratio(r.ax, r.rust),
            r.go
                .map(|g| format!("{:.2}×", ratio(r.ax, g)))
                .unwrap_or_else(|| "—".into()),
            v,
        ));
    }
    md.push('\n');

    md.push_str("## What each row measures\n\n");
    for r in rows {
        md.push_str(&format!(
            "- **{}** (`{}`, n={}): {}\n",
            r.title,
            r.id,
            fmt_n(r.n),
            r.what
        ));
    }
    md.push('\n');

    md.push_str(
        "## How to reproduce\n\n\
         ```\n\
         ax bench software\n\
         ```\n\n\
         Writes this file. Times include process spawn, so rows are sized so the \
         kernel is tens of milliseconds, not a couple of milliseconds of `execve`.\n\n",
    );

    md.push_str(FINDINGS);
    md
}

fn verdict(r: &CaseResult) -> &'static str {
    let rust_ok = within(r.ax, r.rust);
    let c_ok = within(r.ax, r.c);
    let go_ok = r.go.map(|g| within(r.ax, g)).unwrap_or(true);
    if rust_ok && c_ok && go_ok {
        if r.ax <= r.c && r.ax <= r.rust && r.go.map(|g| r.ax <= g).unwrap_or(true) {
            "ax fastest"
        } else {
            "parity"
        }
    } else {
        "ax behind"
    }
}

fn fmt_n(n: u64) -> String {
    if n >= 1_000_000 {
        format!("{}e6", n / 1_000_000)
    } else if n >= 1_000 {
        format!("{}e3", n / 1_000)
    } else {
        n.to_string()
    }
}

fn finish(
    id: &'static str,
    title: &'static str,
    what: &'static str,
    n: u64,
    rows: Vec<Row>,
) -> Result<CaseResult, String> {
    expect_same(id, &rows)?;
    print_group(&format!("{id}   {title}   n={n}"), &rows, Some("c"));
    let pick = |name: &str| {
        rows.iter()
            .find(|r| r.kind == name)
            .map(|r| r.min_ns)
            .unwrap_or(0)
    };
    Ok(CaseResult {
        id,
        title,
        what,
        n,
        ax: pick("ax-native"),
        c: pick("c"),
        rust: pick("rust"),
        go: rows.iter().find(|r| r.kind == "go").map(|r| r.min_ns),
        out: rows
            .iter()
            .find(|r| r.kind == "c")
            .map(|r| r.out.clone())
            .unwrap_or_default(),
    })
}

fn time_langs(
    stem: &str,
    ax_src: &str,
    c_src: &str,
    rs_src: &str,
    go_src: &str,
    args: &[&str],
) -> Result<Vec<Row>, String> {
    let ax = compile_ax(ax_src, &format!("sw_{stem}_ax"))?;
    let c = compile_c(c_src, &format!("sw_{stem}_c"))?;
    let rs = compile_rust(rs_src, &format!("sw_{stem}_rs"))?;
    let (ax_med, ax_ns, ax_out) = time_cmd_stats(&ax, args, ITERS, WARMUP)?;
    let (c_med, c_ns, c_out) = time_cmd_stats(&c, args, ITERS, WARMUP)?;
    let (rs_med, rs_ns, rs_out) = time_cmd_stats(&rs, args, ITERS, WARMUP)?;
    let mut rows = vec![
        Row {
            kind: "c".into(),
            ns: c_med,
            min_ns: c_ns,
            out: c_out,
        },
        Row {
            kind: "rust".into(),
            ns: rs_med,
            min_ns: rs_ns,
            out: rs_out,
        },
        Row {
            kind: "ax-native".into(),
            ns: ax_med,
            min_ns: ax_ns,
            out: ax_out,
        },
    ];
    if go_available() {
        let go = compile_go(go_src, &format!("sw_{stem}"))?;
        let (med, ns, out) = time_cmd_stats(&go, args, ITERS, WARMUP)?;
        rows.push(Row {
            kind: "go".into(),
            ns: med,
            min_ns: ns,
            out,
        });
    }
    Ok(rows)
}

